#!/usr/bin/bash
# Post-run report sync: merge NII's UniProt-derived annotation (gene name,
# description, GO/Pfam/InterPro cross-references -- bin/merge_uniprot_annotations.py)
# into a completed study's presence matrices, regenerate novelties/core/losses.html
# (with --online, so the popup-enabled copy is what actually reaches the gallery --
# see NovInvenio issues #74/#75/#82/#86) against the merged matrix via nf_NovInvenio's
# own bin/make_*_report.py, and copy the result into docs/<domain>/<set>/ (the
# published gallery -- DESIGN.md Sec 8) -- then refresh the gallery index
# (bin/generate_docs.py).
#
# No separate view/ mirror: docs/ already lives on local disk before anything gets
# pushed, so it serves local preview just as well and keeping a second copy was
# pure redundant storage (each study's report set runs tens of MB). report.html,
# summary.pdf, alignment.html, and the alignments/loss_alignments/ shard
# directories, though, are published by nf_NovInvenio's own COLLATE_REPORTS/
# MAKE_PDF_REPORT/BUILD_ALIGNMENT_SHARDS processes to a *different*,
# pipeline-hardcoded location -- Helpers.docsDir() in the pipeline repo writes them
# to a flat $REPO_ROOT/docs/<project>/ (parent-of-outdir + "docs"), independent of
# anything this script does, since that's nf_NovInvenio's own convention and not
# something NII controls without patching the pipeline. This script pulls those out
# of there into the two-tier docs/<domain>/<set>/ and removes the pipeline's flat
# docs/<project>/ afterward, so it doesn't linger as a stale, unmerged-annotation
# duplicate between runs. (Until 2026-09-09 this pulled from a stale $REPO_ROOT/
# view/<project>/ path left over from before nf_NovInvenio's own view/->docs/
# rename -- that directory silently never existed anymore, so report.html/
# summary.pdf had quietly stopped reaching the gallery at all. Fixed alongside
# adding the alignments/ relocation and --online regeneration, see NII issue #5.)
#
# alignments/loss_alignments/ are relocated on local disk only -- they are NOT
# git-committed (see NII issue #3's gitignore rule); a separate publish step
# (NII issue #1) packages them as a GitHub Release asset instead, downloaded and
# merged back into docs/ at Pages-deploy time (NII issue #2) so the committed repo
# never grows from shard data no matter how many times a study reruns.
#
# Run automatically by bin/run_study.sh after a successful nextflow run (see its
# call site). Safe to re-run standalone any time report.html's inputs change
# without a full pipeline relaunch -- e.g. after regenerating annotations/ from a
# refreshed UniProt pull, or after editing the report templates in a local
# nf_NovInvenio checkout (report.html/summary.pdf/alignment.html/the shard
# directories won't be regenerated by a standalone re-run, though -- they only
# come from an actual nextflow run's docs/<project>/ output; this script just
# relocates them).
#
# Usage: NOVINVENIO_ROOT=/path/to/local/NovInvenio bin/sync_reports.sh <domain>/<set_name>
#   NOVINVENIO_ROOT must point at a local nf_NovInvenio/NovInvenio checkout (its
#   bin/make_report.py etc. are invoked directly here, not through nextflow) --
#   same local-checkout requirement as bin/run_study.sh's NII_PIPELINE override.
#
# When a study has no studies/<set>/annotations/ yet (non-UniProt-sourced study --
# e.g. one built via a study-specific bin/build_<study>_config.py instead of the
# shared bin/build_study_config.py -- or bin/build_study_config.py hasn't been
# (re-)run since it started producing them), the UniProt-merge + report-regenerate
# steps are skipped -- but novelties.html/losses.html still come from the pipeline's
# own flat docs/<project>/ output (already --online, since nf_NovInvenio's
# COLLATE_REPORTS always regenerates that copy), not from results/<set>/'s
# always-offline copy, so the gallery stays consistently popup-capable either way.
# core.html has no online/offline divergence (no TBLASTN column) and is always
# taken from results/<set>/. Only a genuine no-op (with a message, not an error):
# no results/<set>/ output yet (pipeline hasn't run).

set -euo pipefail

STUDY="${1:?Usage: bin/sync_reports.sh <domain>/<set_name>}"
NOVINVENIO_ROOT="${NOVINVENIO_ROOT:?Set NOVINVENIO_ROOT to a local nf_NovInvenio/NovInvenio checkout}"

REPO_ROOT="$(cd "$(dirname "${0}")/.." && pwd)"
SET_NAME="$(basename "$STUDY")"
STUDY_DIR="$REPO_ROOT/studies/$STUDY"
RESULTS_DIR="$REPO_ROOT/results/$SET_NAME"
DOCS_DIR="$REPO_ROOT/docs/$STUDY"
# nf_NovInvenio's own hardcoded publishDir for report.html/summary.pdf/
# alignment.html/alignments//loss_alignments/ -- see the module docstring above
# (Helpers.docsDir()). Not ours; just where it lands.
PIPELINE_DOCS_DIR="$REPO_ROOT/docs/$SET_NAME"

if [ ! -f "$RESULTS_DIR/presence_matrix.function.tsv" ]; then
    echo "== $RESULTS_DIR/presence_matrix.function.tsv not found -- run the study first, skipping report sync ==" >&2
    exit 0
fi

HAS_ANNOTATIONS=0
if [ -d "$STUDY_DIR/annotations" ] && [ -n "$(ls -A "$STUDY_DIR/annotations" 2>/dev/null)" ]; then
    HAS_ANNOTATIONS=1
fi

NIIPY() { pixi run --manifest-path "$REPO_ROOT/pixi.toml" python "$REPO_ROOT/bin/$1" "${@:2}"; }
PIPEPY() { pixi run --manifest-path "$NOVINVENIO_ROOT/pixi.toml" python "$NOVINVENIO_ROOT/bin/$1" "${@:2}"; }

if [ "$HAS_ANNOTATIONS" -eq 1 ]; then
    shopt -s nullglob
    ANNOT_TSVS=("$STUDY_DIR"/annotations/*.tsv)
    shopt -u nullglob

    echo "== merging UniProt annotation into $RESULTS_DIR presence matrices ==" >&2
    NIIPY merge_uniprot_annotations.py \
        --matrix "$RESULTS_DIR/presence_matrix.function.tsv" \
        --annotations "${ANNOT_TSVS[@]}" \
        --output "$RESULTS_DIR/presence_matrix.uniprot.tsv" \
        --lenient

    if [ -f "$RESULTS_DIR/loss_presence_matrix.function.tsv" ]; then
        NIIPY merge_uniprot_annotations.py \
            --matrix "$RESULTS_DIR/loss_presence_matrix.function.tsv" \
            --annotations "${ANNOT_TSVS[@]}" \
            --output "$RESULTS_DIR/loss_presence_matrix.uniprot.tsv" \
            --lenient
    fi

    echo "== regenerating novelties.html (--online) ==" >&2
    NOV_ARGS=(
        --matrix "$RESULTS_DIR/presence_matrix.uniprot.tsv"
        --config "$STUDY_DIR/config.csv"
        --project "$SET_NAME"
        --data_dir "$STUDY_DIR/data_dir"
        --sequences novelties
        --online
        --output "$RESULTS_DIR/novelties.html"
    )
    [ -f "$RESULTS_DIR/tblastn_summary.tsv" ] && NOV_ARGS+=(--tblastn_summary "$RESULTS_DIR/tblastn_summary.tsv")
    shopt -s nullglob
    NOV_TSVS=("$RESULTS_DIR"/novelties.*.tsv)
    shopt -u nullglob
    [ ${#NOV_TSVS[@]} -gt 0 ] && NOV_ARGS+=(--novelties "${NOV_TSVS[@]}")
    [ -f "$RESULTS_DIR/candidates.fa" ] && NOV_ARGS+=(--candidates_fa "$RESULTS_DIR/candidates.fa")
    [ -f "$RESULTS_DIR/clusters/clusters_cluster.tsv" ] && NOV_ARGS+=(--cluster_tsv "$RESULTS_DIR/clusters/clusters_cluster.tsv")
    [ -f "$RESULTS_DIR/presence_matrix.evalues.tsv" ] && NOV_ARGS+=(--evalues "$RESULTS_DIR/presence_matrix.evalues.tsv")
    [ -f "$RESULTS_DIR/context_presence.tsv" ] && NOV_ARGS+=(--context_matrix "$RESULTS_DIR/context_presence.tsv")
    [ -f "$RESULTS_DIR/context_presence.evalues.tsv" ] && NOV_ARGS+=(--context_evalues "$RESULTS_DIR/context_presence.evalues.tsv")
    PIPEPY make_report.py "${NOV_ARGS[@]}"

    echo "== regenerating core.html ==" >&2
    CORE_ARGS=(
        --matrix "$RESULTS_DIR/presence_matrix.uniprot.tsv"
        --config "$STUDY_DIR/config.csv"
        --project "$SET_NAME"
        --data_dir "$STUDY_DIR/data_dir"
        --output "$RESULTS_DIR/core.html"
    )
    [ -f "$RESULTS_DIR/clusters/clusters_cluster.tsv" ] && CORE_ARGS+=(--cluster_tsv "$RESULTS_DIR/clusters/clusters_cluster.tsv")
    PIPEPY make_core_report.py "${CORE_ARGS[@]}"

    if [ -f "$RESULTS_DIR/loss_presence_matrix.uniprot.tsv" ]; then
        echo "== regenerating losses.html (--online) ==" >&2
        LOSSES_ARGS=(
            --matrix "$RESULTS_DIR/loss_presence_matrix.uniprot.tsv"
            --config "$STUDY_DIR/config.csv"
            --project "$SET_NAME"
            --data_dir "$STUDY_DIR/data_dir"
            --online
            --output "$RESULTS_DIR/losses.html"
        )
        [ -f "$RESULTS_DIR/loss_tblastn_summary.tsv" ] && LOSSES_ARGS+=(--tblastn_summary "$RESULTS_DIR/loss_tblastn_summary.tsv")
        [ -f "$RESULTS_DIR/clusters/loss_clusters_cluster.tsv" ] && LOSSES_ARGS+=(--cluster_tsv "$RESULTS_DIR/clusters/loss_clusters_cluster.tsv")
        PIPEPY make_losses_report.py "${LOSSES_ARGS[@]}"
    fi
    # Regenerated in place above, --online -- sync straight from $RESULTS_DIR.
    NOV_LOSSES_SRC_DIR="$RESULTS_DIR"
else
    echo "== $STUDY_DIR/annotations empty/missing -- skipping UniProt merge/regenerate ==" >&2
    # No regeneration happened, so results/$SET_NAME/{novelties,losses}.html are
    # nf_NovInvenio's own un-merged, always-offline output. Pull the --online
    # flavor from the pipeline's own flat docs/<project>/ instead (COLLATE_REPORTS
    # always produces it, annotation merge or not) so the gallery stays
    # popup-capable either way rather than silently falling back to offline.
    NOV_LOSSES_SRC_DIR="$PIPELINE_DOCS_DIR"
fi

echo "== syncing reports to $DOCS_DIR ==" >&2
mkdir -p "$DOCS_DIR"
[ -f "$RESULTS_DIR/core.html" ] && cp "$RESULTS_DIR/core.html" "$DOCS_DIR/core.html"
for f in novelties.html losses.html; do
    [ -f "$NOV_LOSSES_SRC_DIR/$f" ] && cp "$NOV_LOSSES_SRC_DIR/$f" "$DOCS_DIR/$f"
done
# report.html/summary.pdf/alignment.html/the shard directories never land in
# $RESULTS_DIR (see PIPELINE_DOCS_DIR above) -- pull them from wherever nextflow
# actually published them, then remove that directory so it doesn't linger as a
# stale, unmerged-annotation duplicate.
if [ -d "$PIPELINE_DOCS_DIR" ]; then
    for f in report.html summary.pdf alignment.html; do
        [ -f "$PIPELINE_DOCS_DIR/$f" ] && cp "$PIPELINE_DOCS_DIR/$f" "$DOCS_DIR/$f"
    done
    # alignments/loss_alignments/: not git-committed (NII issue #3) -- relocated
    # here on local disk only, for NII issue #1's release-asset publish step to
    # package from $DOCS_DIR afterward.
    for d in alignments loss_alignments; do
        [ -d "$PIPELINE_DOCS_DIR/$d" ] && rm -rf "$DOCS_DIR/$d" && cp -r "$PIPELINE_DOCS_DIR/$d" "$DOCS_DIR/$d"
    done
    rm -rf "$PIPELINE_DOCS_DIR"
fi

echo "== refreshing docs/ gallery ==" >&2
NIIPY generate_docs.py

echo "== done: $STUDY report sync complete ==" >&2
